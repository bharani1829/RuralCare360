const LANG_STORAGE_KEY = 'ruralcare_language_v1';

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>('en');

  React.useEffect(() => {
    try {
      const saved = localStorage.getItem(LANG_STORAGE_KEY) as Language;
      if (saved && (saved === 'en' || saved === 'te' || saved === 'hi')) {
        setLanguageState(saved);
      }
    } catch {
      // Ignore localStorage errors in SSR
    }
  }, []);

  // Automatic DOM-wide English-to-Script replacer effect
  React.useEffect(() => {
    if (typeof window === 'undefined') return;
    if (language === 'en') return;

    const dict = language === 'te' ? fullWordDictTE : fullWordDictHI;
    const rawMap = rawPhraseTranslations[language] || {};

    const translateNode = (node: Node) => {
      if (node.nodeType === Node.TEXT_NODE) {
        const text = node.nodeValue;
        if (!text || !/[a-zA-Z]/.test(text)) return;

        const trimmed = text.trim();
        if (rawMap[trimmed]) {
          node.nodeValue = text.replace(trimmed, rawMap[trimmed]);
          return;
        }

        let newText = text;
        Object.keys(dict).forEach((word) => {
          if (newText.includes(word)) {
            const regex = new RegExp(`\\b${word}\\b`, 'g');
            newText = newText.replace(regex, dict[word]);
          }
        });

        if (newText !== text) {
          node.nodeValue = newText;
        }
      } else if (node.nodeType === Node.ELEMENT_NODE) {
        const el = node as HTMLElement;
        if (el.tagName === 'SCRIPT' || el.tagName === 'STYLE' || el.isContentEditable) return;
        el.childNodes.forEach(translateNode);
      }
    };

    const runTranslation = () => {
      translateNode(document.body);
    };

    runTranslation();

    const observer = new MutationObserver((mutations) => {
      mutations.forEach((mutation) => {
        mutation.addedNodes.forEach((node) => translateNode(node));
      });
    });

    observer.observe(document.body, { childList: true, subtree: true });
    return () => observer.disconnect();
  }, [language]);

  const setLanguage = (lang: Language) => {
    if (lang === language) return;
    setLanguageState(lang);
    try {
      localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch {
      // Ignore
    }

    // Reload window on language change to ensure DOM text nodes reset cleanly
    if (typeof window !== 'undefined') {
      window.location.reload();
    }
  };

  const t = (key: string): string => {
    if (!key) return '';

    // 1. Direct raw phrase lookup in rawPhraseTranslations
    if (language !== 'en' && rawPhraseTranslations[language]?.[key]) {
      return rawPhraseTranslations[language][key];
    }

    // 2. Nested key path lookup (e.g. 'nav.dashboard')
    const keys = key.split('.');
    let value: unknown = translations[language];
    for (const k of keys) {
      if (value && typeof value === 'object') {
        value = (value as Record<string, unknown>)[k];
      } else {
        value = undefined;
        break;
      }
    }
    if (typeof value === 'string') return value;

    // 3. Fallback to English nested key lookup
    let fallbackValue: unknown = translations.en;
    for (const k of keys) {
      if (fallbackValue && typeof fallbackValue === 'object') {
        fallbackValue = (fallbackValue as Record<string, unknown>)[k];
      } else {
        fallbackValue = undefined;
        break;
      }
    }
    if (typeof fallbackValue === 'string') return fallbackValue;

    return key;
  };

  const languages: Record<Language, string> = {
    en: 'English',
    te: 'తెలుగు',
    hi: 'हिंदी',
  };

  return React.createElement(
    LanguageContext.Provider,
    { value: { language, setLanguage, t, languages } },
    children
  );
}

export function useTranslation() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error('useTranslation must be used within LanguageProvider');
  }
  return context;
}
